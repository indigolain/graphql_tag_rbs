# frozen_string_literal: true

module GraphqlTagRbs
  # Turns a graphql_tag_pluck operation list into RBS files.
  #
  #   Generator.new(schema: schema, operations: operations).generate
  #   # => { "app/clients/user_client.rbs" => "...", "_shared.rbs" => "..." }
  #
  # Every operation gets a module with `variables`, `data`, and `response`
  # type aliases, and every fragment a module with a `data` alias. Enums,
  # input objects, and the GraphQL error type go into the shared file.
  class Generator
    include Types

    HEADER = "# Generated by graphql_tag_rbs"
    SHARED_FILE = "_shared.rbs"
    KEY_STYLES = %i[string symbol].freeze

    Nodes = GraphQL::Language::Nodes

    Definition = Struct.new(:name, :module_name, :kind, :node, :file, :line, :constant, keyword_init: true) do
      def label = "#{name} (#{file}:#{line})"
    end

    # All occurrences of one response key within a selection set.
    FieldEntry = Struct.new(:name, :nodes, :conditional)

    def initialize(schema:, operations:, namespace: "GraphQLTypes", key_style: :string, scalars: {})
      @schema = schema
      @namespace = namespace.to_s.split("::")
      @key_style = key_style.to_sym
      raise Error, "key_style must be one of #{KEY_STYLES.join(", ")}, got #{key_style.inspect}" unless KEY_STYLES.include?(@key_style)

      @scalars = scalars.to_h { |name, type| [name.to_s, type.to_s] }
      @definitions = build_definitions(operations)
      @fragments = @definitions.select { |d| d.kind == "fragment" }.to_h { |d| [d.name, d.node] }
      @enums = Set.new
      @inputs = Set.new
    end

    def generate
      validate!

      files = @definitions.group_by(&:file).sort.to_h do |file, definitions|
        [output_path(file), render_file(file, definitions.sort_by(&:line))]
      end
      raise Error, "#{SHARED_FILE} clashes with a file generated for a source file; rename that file" if files.key?(SHARED_FILE)

      # Rendered last: rendering the operations collects the enums and inputs it needs.
      files[SHARED_FILE] = render_shared
      files
    end

    private

    # --- Input ------------------------------------------------------------

    def build_definitions(operations)
      definitions = operations.each_value.filter_map do |entry|
        entry = entry.to_h { |key, value| [key.to_s, value] }
        unless entry.key?("file") && entry.key?("line")
          raise Error, "#{entry["name"] || "An operation"} has no file / line. " \
            "Regenerate the operation list with graphql_tag_pluck 0.3.0 or later."
        end

        if entry["name"].nil?
          warn "graphql_tag_rbs: skipping unnamed operation at #{entry["file"]}:#{entry["line"]}; name it to generate types"
          next
        end

        Definition.new(
          name: entry["name"],
          module_name: module_name(entry["name"]),
          kind: entry["type"],
          node: GraphQL.parse(entry["source"]).definitions.first,
          file: entry["file"],
          line: entry["line"],
          constant: entry["constant"]
        )
      end

      definitions.group_by(&:module_name).each do |module_name, same|
        next if same.size == 1

        raise Error, "#{same.map(&:label).join(" and ")} would both generate module #{module_name}"
      end
      definitions
    end

    def validate!
      document = Nodes::Document.new(definitions: @definitions.map(&:node))
      errors = @schema.validate(document).reject do |error|
        # Fragments get their own types, so a fragment no operation spreads is fine.
        error.is_a?(GraphQL::StaticValidation::FragmentsAreUsedError) && error.message.end_with?("was defined, but not used")
      end
      return if errors.empty?

      by_name = @definitions.to_h { |d| [d.name, d] }
      messages = errors.map do |error|
        definition = by_name[error.path&.first.to_s.split(" ").last]
        definition ? "#{definition.label}: #{error.message}" : error.message
      end
      raise Error, "GraphQL validation failed:\n#{messages.map { |m| "  - #{m}" }.join("\n")}"
    end

    # --- Files ------------------------------------------------------------

    def output_path(file)
      "#{file.delete_prefix("/").delete_suffix(".rb")}.rbs"
    end

    def render_file(file, definitions)
      body = definitions.flat_map.with_index do |definition, index|
        (index.zero? ? [] : [""]) + render_definition(definition)
      end
      "#{HEADER} from #{file}. Do not edit.\n\n#{wrap_in_namespace(body)}"
    end

    def render_definition(definition)
      @current = definition
      comment = "# #{definition.kind} #{definition.name} at #{definition.file}:#{definition.line}"
      comment += " (#{definition.constant})" if definition.constant

      aliases =
        if definition.kind == "fragment"
          { "data" => fragment_type(definition.node) }
        else
          { "variables" => variables_type(definition.node), "data" => data_type(definition.node), "response" => response_type }
        end

      lines = [comment, "module #{definition.module_name}"]
      aliases.each_with_index do |(name, type), index|
        lines << "" unless index.zero?
        lines.concat(indent_lines("type #{name} = #{type.render("")}"))
      end
      lines << "end"
    end

    def render_shared
      inputs = {}
      # Input objects can reference further input objects and enums.
      until (pending = @inputs.to_a.sort - inputs.keys).empty?
        pending.each { |name| inputs[name] = input_object_type(@schema.get_type(name)) }
      end

      body = ["type error = #{error_type.render("")}"].flat_map { |line| line.lines(chomp: true) }
      body += shared_module("Enums", @enums.to_a.sort.to_h { |name| [name, enum_type(@schema.get_type(name))] })
      body += shared_module("Inputs", inputs.sort.to_h)

      "#{HEADER}. Do not edit.\n\n#{wrap_in_namespace(body)}"
    end

    def shared_module(module_name, types)
      return [] if types.empty?

      lines = ["", "module #{module_name}"]
      types.each_with_index do |(name, type), index|
        lines << "" unless index.zero?
        lines.concat(indent_lines("type #{alias_name(name)} = #{type.render("")}"))
      end
      lines << "end"
    end

    def wrap_in_namespace(lines)
      @namespace.reverse_each do |name|
        lines = ["module #{name}", *indent_lines(lines), "end"]
      end
      "#{lines.join("\n")}\n"
    end

    def indent_lines(text)
      Array(text)
        .flat_map { |chunk| chunk.empty? ? [""] : chunk.lines(chomp: true) }
        .map { |line| line.empty? ? line : INDENT + line }
    end

    # --- Operation types ----------------------------------------------------

    def data_type(operation)
      root = @schema.root_type_for_operation(operation.operation_type)
      raise Error, "#{@current.label}: the schema has no #{operation.operation_type} type" if root.nil?

      selection_set_type(root, operation.selections, [])
    end

    def fragment_type(fragment)
      selection_set_type(@schema.get_type(fragment.type.name), fragment.selections, [])
    end

    def variables_type(operation)
      fields = operation.variables.map do |variable|
        required = variable.type.is_a?(Nodes::NonNullType) && variable.default_value.nil?
        Field.new(variable.name, input_ast_type(variable.type), !required)
      end
      Record.new(fields, @key_style)
    end

    def response_type
      Record.new([
        Field.new("data", Optional.new(Named.new("data")), true),
        Field.new("errors", ArrayOf.new(Named.new("#{namespace_ref}::error")), true),
        Field.new("extensions", hash_type, true)
      ], @key_style)
    end

    def error_type
      location = Record.new([Field.new("line", Named.new("::Integer"), false), Field.new("column", Named.new("::Integer"), false)], @key_style)
      Record.new([
        Field.new("message", Named.new("::String"), false),
        Field.new("locations", ArrayOf.new(location), true),
        Field.new("path", ArrayOf.new(Union.of([Named.new("::String"), Named.new("::Integer")])), true),
        Field.new("extensions", hash_type, true)
      ], @key_style)
    end

    def hash_type
      Named.new(@key_style == :symbol ? "::Hash[::Symbol, untyped]" : "::Hash[::String, untyped]")
    end

    # --- Selections ---------------------------------------------------------

    # The type of a selection set on `parent_type`. For abstract types, possible
    # types that select the same fields share one record, distinguished by a
    # `__typename` literal union; differing shapes become a union of records.
    def selection_set_type(parent_type, selections, path)
      possible = @schema.possible_types(parent_type).sort_by(&:graphql_name)
      return UNTYPED if possible.empty?

      shapes = possible.map do |type|
        entries = {}
        collect_fields(type, selections, false, entries)
        [type, entries.map { |key, entry| field_for(type, key, entry, path) }]
      end

      groups = shapes.group_by { |_type, fields| fields }.transform_values { |members| members.map(&:first) }
      if groups.size > 1 && !groups.keys.all? { |fields| fields.any? { |field| field.type == :typename } }
        location = path.empty? ? "the root selection" : "`#{path.join(".")}`"
        raise Error, "#{@current.label}: #{location} selects different fields depending on whether the " \
          "#{parent_type.graphql_name} is a #{possible.map(&:graphql_name).join(", ")}; " \
          "select `__typename` there so the result can be told apart"
      end

      Union.of(groups.map do |fields, types|
        typename = Union.of(types.map { |type| Literal.new(type.graphql_name) })
        Record.new(fields.map { |field| field.type == :typename ? Field.new(field.key, typename, field.optional) : field }, @key_style)
      end)
    end

    # Collects the fields `type` gets from `selections`, following inline
    # fragments and fragment spreads that apply to it. Fields under
    # @include / @skip may be missing from the response, so they are marked
    # conditional unless the same key is also selected unconditionally.
    def collect_fields(type, selections, conditional, entries)
      selections.each do |selection|
        selection_conditional = conditional || selection.directives.any? { |d| %w[include skip].include?(d.name) }

        case selection
        when Nodes::Field
          key = selection.alias || selection.name
          if (entry = entries[key])
            entry.nodes << selection
            entry.conditional &&= selection_conditional
          else
            entries[key] = FieldEntry.new(selection.name, [selection], selection_conditional)
          end
        when Nodes::InlineFragment
          next if selection.type && !applies_to?(type, selection.type.name)

          collect_fields(type, selection.selections, selection_conditional, entries)
        when Nodes::FragmentSpread
          fragment = @fragments.fetch(selection.name)
          next unless applies_to?(type, fragment.type.name)

          collect_fields(type, fragment.selections, selection_conditional, entries)
        end
      end
    end

    def applies_to?(type, type_condition)
      condition = @schema.get_type(type_condition)
      condition == type || (condition.kind.abstract? && @schema.possible_types(condition).include?(type))
    end

    def field_for(type, key, entry, path)
      # A placeholder, replaced with the possible type names once types are grouped.
      return Field.new(key, :typename, entry.conditional) if entry.name == "__typename"

      definition = @schema.get_field(type, entry.name)
      field_type = output_type(definition.type, entry.nodes.flat_map(&:selections), path + [key])
      Field.new(key, field_type, entry.conditional)
    end

    def output_type(type, selections, path)
      return bare_output_type(type.of_type, selections, path) if type.non_null?

      Optional.new(bare_output_type(type, selections, path))
    end

    def bare_output_type(type, selections, path)
      return ArrayOf.new(output_type(type.of_type, selections, path)) if type.list?

      case type.kind.name
      when "SCALAR" then scalar_type(type.graphql_name, :output)
      when "ENUM" then enum_ref(type)
      else selection_set_type(type, selections, path)
      end
    end

    # --- Inputs ---------------------------------------------------------------

    def input_ast_type(ast_type)
      return bare_input_ast_type(ast_type.of_type) if ast_type.is_a?(Nodes::NonNullType)

      Optional.new(bare_input_ast_type(ast_type))
    end

    def bare_input_ast_type(ast_type)
      return ArrayOf.new(input_ast_type(ast_type.of_type)) if ast_type.is_a?(Nodes::ListType)

      named_input_type(@schema.get_type(ast_type.name))
    end

    def input_type(type)
      return bare_input_type(type.of_type) if type.non_null?

      Optional.new(bare_input_type(type))
    end

    def bare_input_type(type)
      return ArrayOf.new(input_type(type.of_type)) if type.list?

      named_input_type(type)
    end

    def named_input_type(type)
      case type.kind.name
      when "SCALAR" then scalar_type(type.graphql_name, :input)
      when "ENUM" then enum_ref(type)
      else
        @inputs << type.graphql_name
        Named.new("#{namespace_ref}::Inputs::#{alias_name(type.graphql_name)}")
      end
    end

    def input_object_type(type)
      arguments = type.arguments.values

      # @oneOf input objects take exactly one of their fields, and it must not be null.
      if type.respond_to?(:one_of?) && type.one_of?
        return Union.of(arguments.map do |argument|
          value_type = argument.type.non_null? ? argument.type.of_type : argument.type
          Record.new([Field.new(argument.graphql_name, bare_input_type(value_type), false)], @key_style)
        end)
      end

      Record.new(arguments.map do |argument|
        required = argument.type.non_null? && !argument.default_value?
        Field.new(argument.graphql_name, input_type(argument.type), !required)
      end, @key_style)
    end

    # --- Leaves ---------------------------------------------------------------

    BUILT_IN_SCALARS = {
      output: { "ID" => "::String", "String" => "::String", "Int" => "::Integer", "Float" => "::Float", "Boolean" => "bool" },
      # Input coercion also accepts integers for ID and Float.
      input: { "ID" => "::String | ::Integer", "String" => "::String", "Int" => "::Integer", "Float" => "::Float | ::Integer", "Boolean" => "bool" }
    }.freeze

    def scalar_type(name, direction)
      Named.new(@scalars.fetch(name) { BUILT_IN_SCALARS[direction].fetch(name, "untyped") })
    end

    def enum_ref(type)
      @enums << type.graphql_name
      Named.new("#{namespace_ref}::Enums::#{alias_name(type.graphql_name)}")
    end

    def enum_type(type)
      Union.of(type.values.keys.map { |value| Literal.new(value) })
    end

    # --- Naming ---------------------------------------------------------------

    def namespace_ref = "::#{@namespace.join("::")}"

    # GraphQL names may start with a lowercase letter or underscores; RBS module names may not.
    def module_name(name)
      stripped = name.sub(/\A_+/, "")
      module_name = stripped[0].to_s.upcase + stripped[1..].to_s
      raise Error, "Cannot turn GraphQL name #{name.inspect} into an RBS module name" unless module_name.match?(/\A[A-Z]\w*\z/)
      raise Error, "#{name} clashes with the generated #{module_name} module; rename it" if %w[Enums Inputs].include?(module_name)

      module_name
    end

    # RBS type alias names start with a lowercase letter: UserRole => user_role.
    def alias_name(name)
      name.sub(/\A_+/, "").gsub(/([A-Z]+)([A-Z][a-z])/, '\1_\2').gsub(/([a-z\d])([A-Z])/, '\1_\2').downcase
    end
  end
end
